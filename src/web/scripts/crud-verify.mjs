import { chromium } from 'playwright'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
const log = (...a) => console.log(...a)
const errors = []
page.on('pageerror', e => errors.push('PAGEERROR ' + e.message))

const uid = Date.now().toString().slice(-6)
const churchName = `QA CHURCH ${uid}`
const churchRenamed = `QA CHURCH RENAMED ${uid}`
const memberFirst = 'QaFirst'
const memberLast = `QaLast${uid}`
const annTitle = `QA Announcement ${uid}`
const annEdited = `QA Announcement Edited ${uid}`

async function login() {
  await page.goto('http://localhost:3000/login')
  await page.getByLabel('Username').fill('super-admin')
  await page.getByLabel('Password').fill('super-admin')
  await page.getByRole('button', { name: 'Sign In' }).click()
  await page.waitForURL(/\/dashboard/, { timeout: 20000 })
  await page.waitForTimeout(1500)
}

await login()

// ---------- CHURCH ----------
await page.goto('http://localhost:3000/churches')
await page.waitForTimeout(1500)
await page.getByRole('button', { name: 'Create Church' }).click()
const cd = page.locator('.mf-dialog')
await cd.locator('input.mf-input').first().fill(churchName)
await cd.locator('textarea.mf-input').first().fill('12 QA Street')
await cd.getByRole('button', { name: /Save/i }).click()
await page.waitForTimeout(2500)
log('CHURCH create toast:', await page.locator('.swal2-toast, .swal2-popup, #_rht_toaster').allTextContents().catch(() => []))
log('CHURCH created visible:', (await page.locator('body').innerText()).includes(churchName))
log('CHURCH URL:', page.url())

const search = page.getByPlaceholder('Search churches by name or address')
await search.fill(churchName)
await page.waitForTimeout(1500)
log('CHURCH search visible:', (await page.locator('body').innerText()).includes(churchName))
const editCard = page.locator('div').filter({ hasText: churchName }).filter({ has: page.getByTitle('Edit') }).last()
log('CHURCH card count', await editCard.count())
await editCard.getByTitle('Edit').click()
await page.waitForTimeout(500)
const ed = page.locator('.mf-dialog')
log('CHURCH edit title:', await ed.locator('.mf-header-title').innerText())
await ed.locator('input.mf-input').first().fill(churchRenamed)
await ed.getByRole('button', { name: /Save/i }).click()
await page.waitForTimeout(2500)
await search.fill(churchRenamed)
await page.waitForTimeout(1500)
log('CHURCH edit visible:', (await page.locator('body').innerText()).includes(churchRenamed))

const delCard = page.locator('div').filter({ hasText: churchRenamed }).filter({ has: page.getByTitle('Delete') }).last()
log('CHURCH delete card count', await delCard.count())
await delCard.getByTitle('Delete').click()
await page.waitForTimeout(700)
log('CHURCH delete dialog:', (await page.locator('.dialog-overlay .dialog').last().innerText()).slice(0, 200))
await page.locator('.dialog-overlay .dialog').last().locator('.btn-danger').click()
await page.waitForTimeout(2500)
await search.fill(churchRenamed)
await page.waitForTimeout(1500)
log('CHURCH after delete visible:', (await page.locator('body').innerText()).includes(churchRenamed))

// ---------- MEMBER ----------
await page.goto('http://localhost:3000/members')
await page.waitForTimeout(2000)
await page.getByRole('button', { name: 'Add Member' }).click()
await page.waitForTimeout(500)
const md = page.locator('.mf-dialog')
const inputs = md.locator('input.mf-input')
log('MEMBER input count', await inputs.count())
await inputs.nth(0).fill(memberFirst)
await inputs.nth(1).fill(memberLast)
await md.locator('select.mf-input').first().selectOption('Male')
await md.locator('select.mf-input').nth(1).selectOption({ label: 'ALAGOMEJI' })
await inputs.nth(3).fill('1 QA Avenue')
await inputs.nth(4).fill('qa@example.com')
await inputs.nth(5).fill('08012345678')
await md.getByRole('button', { name: /Save/i }).click()
await page.waitForTimeout(3000)
log('MEMBER create toast:', await page.locator('.swal2-toast, .swal2-popup, #_rht_toaster').allTextContents().catch(() => []))
log('MEMBER dialog still open:', await md.isVisible().catch(() => false))
log('MEMBER body has:', (await page.locator('body').innerText()).includes(memberLast))
const msearch = page.getByPlaceholder('Search by name, email or phone')
await msearch.fill(memberLast)
await page.waitForTimeout(2000)
log('MEMBER search has:', (await page.locator('body').innerText()).includes(memberLast))
const row = page.locator('tr').filter({ hasText: memberLast }).first()
log('MEMBER row buttons:', await row.locator('button').count())
await row.locator('button[data-tooltip="Edit"]').click()
await page.waitForTimeout(500)
const med = page.locator('.mf-dialog')
log('MEMBER edit title:', await med.locator('.mf-header-title').innerText())
await med.getByRole('button', { name: /Cancel/i }).click()
await page.waitForTimeout(300)
await page.locator('tr').filter({ hasText: memberLast }).first().locator('button[data-tooltip="Delete"]').click()
await page.waitForTimeout(500)
log('MEMBER delete dialog:', (await page.locator('.dialog-overlay .dialog').last().innerText().catch(() => '')).slice(0, 200))
await page.locator('.dialog-overlay .dialog').last().getByRole('button', { name: /Confirm|Delete|Yes/i }).click().catch(async () => {
  await page.locator('.dialog-overlay .dialog .btn-danger').click()
})
await page.waitForTimeout(2500)
await msearch.fill(memberLast)
await page.waitForTimeout(1500)
log('MEMBER after delete visible:', (await page.locator('body').innerText()).includes(memberLast))

// ---------- ANNOUNCEMENT ----------
await page.goto('http://localhost:3000/announcements')
await page.waitForTimeout(2000)
await page.getByRole('button', { name: 'New Announcement' }).click()
await page.waitForTimeout(500)
const ad = page.locator('.announcement-dialog')
await ad.locator('#ann-title').fill(annTitle)
await ad.locator('#ann-content').fill('QA automated announcement content body.')
await ad.getByRole('radio', { name: 'URGENT' }).click()
await ad.locator('#ann-expires').fill('2027-12-31T10:00')
const roleChips = ad.locator('.role-chip')
log('ANN role chips', await roleChips.count())
if (await roleChips.count()) await roleChips.first().click()
await ad.getByRole('button', { name: /Save/i }).click()
await page.waitForTimeout(2500)
log('ANN create toast:', await page.locator('.swal2-toast, .swal2-popup, #_rht_toaster').allTextContents().catch(() => []))
log('ANN created visible:', (await page.locator('body').innerText()).includes(annTitle))
const asearch = page.getByPlaceholder(/search announcements/i)
await asearch.fill(annTitle)
await page.waitForTimeout(500)
const arow = page.locator('tr').filter({ hasText: annTitle }).first()
await arow.getByLabel('View').click()
await page.waitForTimeout(500)
log('ANN view modal text:', (await page.locator('.announcement-dialog').innerText()).slice(0, 500))
await page.locator('.announcement-dialog').getByRole('button', { name: 'Done' }).click()
await page.waitForTimeout(300)
await arow.getByLabel('Edit').click()
await page.waitForTimeout(500)
log('ANN edit title:', await page.locator('.announcement-dialog h3').first().innerText())
await page.locator('#ann-title').fill(annEdited)
await page.locator('.announcement-dialog').getByRole('button', { name: /Save Changes/i }).click()
await page.waitForTimeout(2500)
await asearch.fill(annEdited)
await page.waitForTimeout(500)
log('ANN edit visible:', (await page.locator('body').innerText()).includes(annEdited))
await page.locator('tr').filter({ hasText: annEdited }).first().getByLabel('Delete').click()
await page.waitForTimeout(500)
log('ANN delete dialog:', (await page.locator('.swal2-popup').innerText()).slice(0, 200))
await page.locator('.swal2-confirm').click()
await page.waitForTimeout(2500)
await asearch.fill(annEdited)
await page.waitForTimeout(500)
log('ANN after delete visible:', (await page.locator('body').innerText()).includes(annEdited))

// ---------- SETTINGS ----------
await page.goto('http://localhost:3000/settings')
await page.waitForTimeout(2000)
log('SETTINGS tabs:', await page.locator('.settings-tab').allTextContents())
log('SETTINGS role names:', await page.locator('.settings-card-name').allTextContents())
await page.locator('.settings-card').filter({ hasText: 'MEMBER BAPTISED' }).first().getByTitle('Edit').click()
await page.waitForTimeout(500)
log('SETTINGS edit visible:', await page.getByText('Edit role permissions').isVisible().catch(() => false))
await page.locator('.settings-panel').getByRole('button', { name: 'Cancel' }).first().click()
await page.waitForTimeout(300)

// ---------- PROFILE ----------
await page.goto('http://localhost:3000/profile')
await page.waitForTimeout(1500)
log('PROFILE tabs:', await page.locator('.tab').allTextContents())
await page.getByRole('button', { name: 'Security' }).click()
await page.locator('input[name="currentPassword"]').fill('super-admin')
await page.locator('input[name="newPassword"]').fill('abcdefgh1')
await page.locator('input[name="confirmPassword"]').fill('abcdefgh2')
await page.getByRole('button', { name: /Update Password/i }).click()
await page.waitForTimeout(1200)
log('PROFILE mismatch toast:', await page.locator('.swal2-toast, .swal2-popup').allTextContents().catch(() => []))

// ---------- ACCESS CONTROL ----------
for (const route of ['/pastors', '/elders', '/deacons', '/contributions', '/projects', '/notifications', '/admins']) {
  await page.goto('http://localhost:3000' + route)
  await page.waitForTimeout(700)
  log('ACCESS', route, '->', page.url())
}

log('PAGE ERRORS', errors)
await browser.close()
