import { beforeEach, describe, expect, it, vi } from 'vitest'

vi.mock('react-hot-toast', () => ({ default: { error: vi.fn(), success: vi.fn() } }))

function jsonResponse(body: unknown, status = 200) {
  return { ok: status >= 200 && status < 300, status, text: async () => JSON.stringify(body), json: async () => body } as any
}

describe('api wrappers', () => {
  beforeEach(() => {
    vi.resetModules()
    vi.clearAllMocks()
    localStorage.clear()
    ;(globalThis as any).fetch = vi.fn().mockResolvedValue(jsonResponse({ data: {} }))
  })

  it('calls auth/profile/roles/config endpoints', async () => {
    const api = await import('./api')
    localStorage.setItem('accessToken', 't')
    await api.authApi.register({ username: 'u', password: 'p' })
    await api.authApi.login({ username: 'u', password: 'p' })
    await api.authApi.refreshToken({ refreshToken: 'r' })
    await api.authApi.logout({ accessToken: 'a', refreshToken: 'r' })
    await api.authApi.requestPasswordReset({ phoneNumber: '1' })
    await api.authApi.confirmPasswordReset({ phoneNumber: '1', otp: '123', newPassword: 'x' })
    await api.authApi.changePassword({ currentPassword: 'a', newPassword: 'b' })
    await api.authApi.listUsers()
    await api.authApi.assignRole('1', 'ADMIN', '1')
    await api.authApi.revokeRole('1', 'ADMIN')
    await api.authApi.setUserStatus('1', 'DISABLED')
    await api.authApi.setDirectPermissions('1', ['A:B'], true)
    await api.authApi.getMyPermissions()
    await api.profileApi.getProfile()
    await api.profileApi.updateProfile({ firstName: 'A', lastName: 'B', tel: '1' })
    await api.rolesApi.list()
    await api.rolesApi.create({ name: 'R', permissions: [] })
    await api.rolesApi.update('1', { name: 'R', permissions: [] })
    await api.rolesApi.delete('1')
    await api.configApi.get()
    await api.configApi.update({ churchName: 'C', churchAddress: 'A', defaultCurrency: 'NGN' })
    await api.configApi.list()
    await api.configApi.upsert('K', 'V', 'd')
    expect((globalThis.fetch as any).mock.calls.length).toBeGreaterThan(20)
  })

  it('calls church/people/pastor/elder/deacon/announcement/audit wrappers', async () => {
    const api = await import('./api')
    ;(globalThis.fetch as any)
      .mockResolvedValueOnce(jsonResponse({ data: { content: [], totalElements: 0, totalPages: 0, size: 20, number: 0 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: {} }))
      .mockResolvedValueOnce(jsonResponse({ data: { content: [], totalElements: 0, totalPages: 0, size: 20, number: 0 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { content: [], totalElements: 0, totalPages: 0, size: 20, number: 0 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: {} }))
      .mockResolvedValueOnce(jsonResponse({ data: true }))
      .mockResolvedValueOnce(jsonResponse({ data: false }))
      .mockResolvedValueOnce(jsonResponse({ data: { content: [{ id: 1, firstName: 'P', lastName: 'L', gender: 'M', tel: '1', church: { id: 1, name: 'C' }, pastorRole: { id: 1, name: 'P' } }] } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'P', lastName: 'L', gender: 'F', tel: '1' } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'P', lastName: 'L' } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'P', lastName: 'L' } }))
      .mockResolvedValueOnce(jsonResponse({ data: {} }))
      .mockResolvedValueOnce(jsonResponse({ data: { content: [] } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'E', lastName: 'L' } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'E', lastName: 'L' } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'E', lastName: 'L' } }))
      .mockResolvedValueOnce(jsonResponse({ data: {} }))
      .mockResolvedValueOnce(jsonResponse({ data: { content: [] } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'D', lastName: 'L' } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'D', lastName: 'L' } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1, firstName: 'D', lastName: 'L' } }))
      .mockResolvedValueOnce(jsonResponse({ data: {} }))
      .mockResolvedValueOnce(jsonResponse({ data: { content: [], totalElements: 0, totalPages: 0, size: 20, number: 0 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { content: [], totalElements: 0, totalPages: 0, size: 20, number: 0 } }))
      .mockResolvedValueOnce(jsonResponse({ data: [] }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: { id: 1 } }))
      .mockResolvedValueOnce(jsonResponse({ data: {} }))
      .mockResolvedValueOnce(jsonResponse({ data: { content: [], total: 0, page: 0, size: 20 } }))

    await api.churchApi.list()
    await api.churchApi.get(1)
    await api.churchApi.create({ name: 'C', address: 'Addr' })
    await api.churchApi.update(1, { name: 'C', address: 'Addr' })
    await api.churchApi.delete(1)
    await api.peopleApi.list({ page: 0, size: 10, search: 'a', position: 'PASTOR', sort: 'name,asc', baptised: 'true' })
    await api.peopleApi.search('a', 0, 10)
    await api.peopleApi.get('1')
    await api.peopleApi.create({ firstName: 'A' })
    await api.peopleApi.update('1', { firstName: 'A' })
    await api.peopleApi.delete('1')
    await api.peopleApi.makeChurchAdmin('1')
    await api.peopleApi.hasChurchAdmin(1)
    const pastors = await api.pastorsApi.list()
    expect(pastors.data?.[0].gender).toBe('Male')
    await api.pastorsApi.get('1')
    await api.pastorsApi.create({ memberId: 1, pastorRoleId: 1, churchId: 1 })
    await api.pastorsApi.update('1', { memberId: 1, pastorRoleId: 1, churchId: 1 })
    await api.pastorsApi.delete('1')
    await api.eldersApi.list()
    await api.eldersApi.get('1')
    await api.eldersApi.create({ memberId: 1 })
    await api.eldersApi.update('1', { firstName: 'E', tel: '1', church: { id: 1, name: 'C', address: '' } })
    await api.eldersApi.delete('1')
    await api.deaconsApi.list()
    await api.deaconsApi.get('1')
    await api.deaconsApi.create({ memberId: 1 })
    await api.deaconsApi.update('1', { firstName: 'D' })
    await api.deaconsApi.delete('1')
    await api.deaconsApi.search('q', 0, 10)
    await api.announcementApi.list()
    await api.announcementApi.get('1')
    await api.announcementApi.create({ title: 't', message: 'm', sendEmail: false, churchId: 1 })
    await api.announcementApi.update('1', { title: 't', message: 'm', sendEmail: false, churchId: 1 })
    await api.announcementApi.delete('1')
    await api.auditApi.list({ page: 0, size: 20, action: 'A' })
  })
})
